const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
let n = 0;
const body = sections
  .map(([title, rows]) => {
    const trs = rows
      .map(([what, expect, skip]) => {
        n += 1;
        const result = expect === null ? '' : `<span class="cb"></span>Ок <span class="cb"></span>Не ок${skip ? ` <span class="cb"></span>${esc(skip)}` : ''}`;
        const exp = expect === null ? '<td class="small">Напишите свободно в заметках ниже.</td>' : `<td>${esc(expect)}</td>`;
        return `<tr><td class="n">${n}</td><td>${esc(what)}</td>${exp}<td class="r">${result}</td><td class="note"></td></tr>`;
      })
      .join('\n');
    return `<h2>${esc(title)}</h2>\n<table><tr><th>№</th><th>Что сделать</th><th>Как должно быть</th><th>Результат</th><th>Заметка</th></tr>\n${trs}</table>`;
  })
  .join('\n\n');

